const THIRD = { maj: 4, min: 3, dom: 4 }, SIX7 = { maj: 9, min: 10, dom: 10 };

/** Every event of `loops` passes of a sketch, in time order. {t beats, kind, midi?, notes?, dur beats, vel}. */
export function eventsFor(key, loops = 1) {
  const d = T[key];
  if (!d) throw new Error(`no sketch ${key}`);
  const bars = d.bars || BARS;
  const out = [];
  const lag = (step) => (step % 4 === 2 ? (d.swing - 0.5) * 0.5 : 0); // the off 8ths land late when the sketch swings
  const at = (bar, step) => bar * 4 + step / 4 + lag(step);
  for (let L = 0; L < loops; L++) {
    const b0 = L * bars;
    for (let bar = 0; bar < bars; bar++) {
      const chord = d.chords[bar], root = d.roots[bar], q = d.q[bar];
      for (const [kind, hits] of Object.entries(d.drums)) for (const [s, v] of hits) out.push({ t: at(b0 + bar, s), kind, dur: kind === 'hatOpen' ? 0.5 : 0.25, vel: v });
      if (d.walk) [0, THIRD[q], 7, SIX7[q]].forEach((o, i) => out.push({ t: at(b0 + bar, i * 4), kind: 'bass', midi: root + o, dur: 0.95, vel: i === 0 ? 0.85 : 0.7 }));
      else for (const [s, o, len, v] of d.bass) out.push({ t: at(b0 + bar, s), kind: 'bass', midi: root + o, dur: len / 4, vel: v });
      for (const [s, len, v] of d.comp) out.push({ t: at(b0 + bar, s), kind: 'chord', notes: chord, dur: len / 4, vel: v });
      if (d.arp) for (let s = 0; s < STEPS; s++) { const n = chord.length, i = s % (2 * n), m = chord[i % n] + (i >= n ? 12 : 0); out.push({ t: at(b0 + bar, s), kind: 'arp', midi: m + 12, dur: 0.22, vel: s % 4 === 0 ? 0.5 : 0.35 }); }
      for (const [b, s, m, len] of d.lead) if (b === bar) out.push({ t: at(b0 + bar, s), kind: 'lead', midi: m, dur: len / 4 - 0.03 - lag(s), vel: s === 0 ? 0.8 : 0.7 }); // a swung start still ends on the grid
    }
  }
  return out.sort((a, b) => a.t - b.t);
}

/** Seconds per loop at the sketch's tempo. */
export const barsOf = (key) => T[key].bars || BARS;
export const loopSeconds = (key, bpm = T[key].bpm) => (barsOf(key) * 4 * 60) / bpm;
